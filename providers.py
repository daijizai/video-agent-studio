"""Provider contract. Intentionally no paid implementation or credentials."""
from typing import Protocol, Dict, Any
class VideoProvider(Protocol):
    def estimate(self, shot: Dict[str, Any]) -> float: ...
    def submit(self, shot: Dict[str, Any], idempotency_key: str) -> str: ...
    def status(self, provider_task_id: str) -> Dict[str, Any]: ...
